def shared_counter():
    reads = []
    for side in ("a", "b"):
        reads.append(
            fn(
                f"read-{side}",
                [],
                I64,
                [
                    blk(
                        "entry",
                        [
                            ("gaddr", "%p", ".counter"),
                            ("bitcast", "%q", Ptr(I8), Ptr(I64), "%p"),
                            ("load", "%v", I64, "%q"),
                        ],
                        ("ret", I64, "%v"),
                    )
                ],
                symbol=f"lg.m.read-{side}",
                internal=True,
            )
        )
    return module([IrGlobal(".counter", b"counter!")], reads)


