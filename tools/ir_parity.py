#: ``pbase`` (only the constructors use that) and none of the ``tp*`` run.
EMIT_ARGS = (
    ["mtriple", "mqual"]
    + ["tags", "names", "elem", "extra", "powner"]
    + ["snames", "sbase", "scount", "sftys"]
    + ["enames", "ewords", "gnames", "gdata"]
    + ["dnames", "dsig", "dcnt", "dret", "sigtys"]
    + ["fnames", "fsyms", "fint", "fret", "fbase", "fcnt", "fparam", "fpc"]
    + ["pnames", "ptys"]
    + ["blabels"] + BLOCK_COLS
    + ROWS
    + RUNS
    + ["out"]
)

TERM_ARGS = ["ops"] + BLOCK_COLS


def logos_str(text: str) -> str:
    """A Logos string literal; only the escapes the lexer knows."""
    out = []
    for byte in text.encode("utf-8"):
        if byte == 0x5C:
            out.append("\\\\")
        elif byte == 0x22:
            out.append('\\"')
        elif byte == 0x0A:
            out.append("\\n")
        elif byte == 0x09:
            out.append("\\t")
        elif byte == 0x0D:
            out.append("\\r")
        elif byte == 0x00:
            out.append("\\0")
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            raise SystemExit(f"a Logos literal cannot spell byte {byte:#04x} of {text!r}")
    return '"' + "".join(out) + '"'


def call(name, vectors, args) -> str:
    return "(" + " ".join([name] + list(vectors) + [str(a) for a in args]) + ")"


def children(ty):
    if isinstance(ty, (Ptr, Own, Ref, Vec, Opt, Shared, Chan, Atomic, Arr)):
        return [ty.elem]
    if isinstance(ty, Res):
        return [ty.ok, ty.err]
    if isinstance(ty, FnTy):
        return list(ty.params) + [ty.ret]
    return []


TY_CLASSES = {
    "Prim",
    "Ptr",
    "Own",
    "Arr",
    "Vec",
    "Ref",
    "Res",
    "Opt",
    "FnTy",
    "Shared",
    "Chan",
    "Atomic",
    "StructRef",
    "EnumRef",
}


def is_ty(value) -> bool:
    return value.__class__.__name__ in TY_CLASSES


def instr_types(instr):
    found = []

    def walk(value):
        if is_ty(value):
            found.append(value)
        elif isinstance(value, (tuple, list)):
            for item in value:
                walk(item)

    walk(instr[1:])
    return found


class Translation:
    """One module, translated into the calls that rebuild it in the arena."""

    def __init__(self, qual: bool = False):
        self.qual = qual
        self.types: dict[str, str] = {}
        self.type_lines: list[str] = []
        self.lines: list[str] = []

    def ty(self, ty) -> str:
        key = repr(ty)
        if key in self.types:
            return self.types[key]
        for child in children(ty):
            self.ty(child)
        name = f"ty{len(self.types)}"
        self.types[key] = name
        self.type_lines.append(self.type_constructor(name, ty))
        return name

    def type_owner(self, name: str) -> str:
        """The declaring module recorded beside a final, qualified name.

        A qualified unit's arena carries the final spelling and, for a
        diagnostic, the module that declared it. ``emit`` must not read the
        second: the name is already complete.
        """
        if not self.qual or "." not in name:
            return ""
        return name.rsplit(".", 1)[0]

    def type_constructor(self, name, ty) -> str:
        arena = TYPES_ARENA
        if isinstance(ty, Prim):
            return f"  (let {name} :i64 {call('type-prim', arena, [logos_str(ty.name)])})"
        if isinstance(ty, StructRef):
            return (
                f"  (let {name} :i64 "
                + call("type-struct", arena, [logos_str(ty.name), logos_str(self.type_owner(ty.name)), -1, 0])
                + ")"
            )
        if isinstance(ty, EnumRef):
            return (
                f"  (let {name} :i64 "
                + call("type-enum", arena, [logos_str(ty.name), logos_str(self.type_owner(ty.name)), -1, 0])
                + ")"
            )
        if isinstance(ty, TypeVar):
            return f"  (let {name} :i64 {call('type-var', arena, [logos_str(ty.name)])})"
        if isinstance(ty, FnTy):
            start = f"ps{len(self.types)}"
            head = "fn*" if ty.captures else "fn"
            block = [f"  (let {start} :i64 (type-param-start tptypes))"]
            for param in ty.params:
                block.append(
                    "  " + call("type-param", ["tpnames", "tptypes"], ['""', self.ty(param)])
                )
            block.append(
                f"  (let {name} :i64 "
                + call(
                    "type-fn", arena, [logos_str(head), self.ty(ty.ret), len(ty.params), start]
                )
                + ")"
            )
            return "\n".join(block)
        unary = {
            Ptr: "type-ptr",
            Own: "type-own",
            Vec: "type-vec",
            Ref: "type-ref",
            Opt: "type-opt",
            Shared: "type-shared",
            Chan: "type-chan",
            Atomic: "type-atomic",
        }
        for cls, head in unary.items():
            if isinstance(ty, cls):
                return f"  (let {name} :i64 {call(head, arena, [self.ty(ty.elem)])})"
        if isinstance(ty, Arr):
            return f"  (let {name} :i64 {call('type-arr', arena, [self.ty(ty.elem), ty.n])})"
        if isinstance(ty, Res):
            return (
                f"  (let {name} :i64 "
                + call("type-res", arena, [self.ty(ty.ok), self.ty(ty.err)])
                + ")"
            )
        raise SystemExit(f"no Logos constructor for type {ty}")

    def instr(self, t) -> list[str]:
        op = t[0]
        row = ROWS + RUNS
        if op == "alloca":
            return ["  " + call("ir-alloca", row, [logos_str(t[1]), self.ty(t[2])])]
        if op == "store":
            return ["  " + call("ir-store", row, [self.ty(t[1]), logos_str(t[2]), logos_str(t[3])])]
        if op == "load":
            return ["  " + call("ir-load", row, [logos_str(t[1]), self.ty(t[2]), logos_str(t[3])])]
        if op == "gaddr":
            return ["  " + call("ir-gaddr", row, [logos_str(t[1]), logos_str(t[2])])]
        if op in BINARIES:
            return [
                "  "
                + call(
                    "ir-binary",
                    row,
                    [
                        f"(ir-op-{op})",
                        logos_str(t[1]),
                        self.ty(t[2]),
                        logos_str(t[3]),
                        logos_str(t[4]),
                    ],
                )
            ]
        if op in ("icmp", "fcmp"):
            return [
                "  "
                + call(
                    f"ir-{op}",
                    row,
                    [
                        logos_str(t[1]),
                        logos_str(t[2]),
                        self.ty(t[3]),
                        logos_str(t[4]),
                        logos_str(t[5]),
                    ],
                )
            ]
        if op == "phi":
            out = ["  " + call("ir-phi", row, [logos_str(t[1]), self.ty(t[2])])]
            for value, label in t[3]:
                out.append(
                    "  "
                    + call(
                        "ir-phi-in", ["ops", "scn", "svals"], [logos_str(value), logos_str(label)]
                    )
                )
            return out
        if op == "insertvalue":
            return [
                "  "
                + call(
                    "ir-insertvalue",
                    row,
                    [
                        logos_str(t[1]),
                        self.ty(t[2]),
                        logos_str(t[3]),
                        self.ty(t[4]),
                        logos_str(t[5]),
                        t[6],
                    ],
                )
            ]
        if op == "extractvalue":
            return [
                "  "
                + call(
                    "ir-extractvalue",
                    row,
                    [logos_str(t[1]), self.ty(t[2]), logos_str(t[4]), self.ty(t[3]), t[5]],
                )
            ]
        if op == "gep":
            out = ["  " + call("ir-gep", row, [logos_str(t[1]), self.ty(t[2]), logos_str(t[3])])]
            for index_ty, index in t[4]:
                out.append(
                    "  "
                    + call(
                        "ir-gep-index",
                        ["ops", "scn", "svals"],
                        [logos_str(index_ty), logos_str(index)],
                    )
                )
            return out
        if op in CONVERTS:
            return [
                "  "
                + call(
                    "ir-convert",
                    row,
                    [
                        f"(ir-op-{op})",
                        logos_str(t[1]),
                        self.ty(t[2]),
                        self.ty(t[3]),
                        logos_str(t[4]),
                    ],
                )
            ]
        if op == "bitcast":
            return [
                "  "
                + call(
                    "ir-bitcast",
                    row,
                    [logos_str(t[1]), self.ty(t[2]), self.ty(t[3]), logos_str(t[4])],
                )
            ]
        if op == "call":
            out = ["  " + call("ir-call", row, [logos_str(t[1]), logos_str(t[2])])]
            for arg in t[3]:
                out.append("  " + call("ir-call-arg", ["ops", "scn", "svals"], [logos_str(arg)]))
            return out
        if op == "allocarec":
            out = ["  " + call("ir-allocarec", row, [logos_str(t[1])])]
            for field in t[2]:
                out.append("  " + call("ir-rec-field", ["ops", "tcn", "tvals"], [self.ty(field)]))
            return out
        if op == "geprec":
            out = ["  " + call("ir-geprec", row, [logos_str(t[1]), logos_str(t[3]), t[4]])]
            for field in t[2]:
                out.append("  " + call("ir-rec-field", ["ops", "tcn", "tvals"], [self.ty(field)]))
            return out
        if op in ("bitcastrec", "bitcastout"):
            name = "ir-bitcastrec" if op == "bitcastrec" else "ir-bitcastout"
            out = ["  " + call(name, row, [logos_str(t[1]), self.ty(t[3]), logos_str(t[4])])]
            for field in t[2]:
                out.append("  " + call("ir-rec-field", ["ops", "tcn", "tvals"], [self.ty(field)]))
            return out
        if op == "faddr":
            return ["  " + call("ir-faddr", row, [logos_str(t[1]), logos_str(t[2])])]
        if op == "fnptr":
            out = ["  " + call("ir-fnptr", row, [logos_str(t[1]), self.ty(t[2]), logos_str(t[4])])]
            for param in t[3]:
                out.append(
                    "  " + call("ir-fnptr-param", ["ops", "tcn", "tvals"], [self.ty(param)])
                )
            return out
        if op == "icall":
            out = [
                "  "
                + call("ir-icall", row, [logos_str(t[1]), self.ty(t[2]), logos_str(t[4])])
            ]
            for param in t[3]:
                out.append(
                    "  " + call("ir-icall-param", ["ops", "tcn", "tvals"], [self.ty(param)])
                )
            for arg in t[5]:
                out.append("  " + call("ir-icall-arg", ["ops", "scn", "svals"], [logos_str(arg)]))
            return out
        raise SystemExit(f"no Logos constructor for opcode {op!r}")

    def term(self, term) -> str:
        op = term[0]
        if op == "ret":
            if term[2] is None:
                return "  " + call("ir-ret-void", TERM_ARGS, [self.ty(term[1])])
            return "  " + call("ir-ret", TERM_ARGS, [self.ty(term[1]), logos_str(term[2])])
        if op == "br":
            return "  " + call("ir-br", TERM_ARGS, [logos_str(term[1])])
        if op == "cbr":
            return "  " + call(
                "ir-cbr",
                TERM_ARGS,
                [logos_str(term[1]), logos_str(term[2]), logos_str(term[3])],
            )
        if op == "unreachable":
            return "  " + call("ir-unreachable", TERM_ARGS, [])
        raise SystemExit(f"no Logos constructor for terminator {op!r}")

    def build(self, m: IrModule) -> str:
        for struct in m.structs:
            for field in struct.fields:
                self.ty(field)
        for decl in m.declares:
            for param in decl.params:
                self.ty(param)
            self.ty(decl.ret)
        for fn_ in m.functions:
            self.ty(fn_.ret)
            for _, ty in fn_.params:
                self.ty(ty)
            for block in fn_.blocks:
                for instr in block.instrs:
                    for ty in instr_types(instr):
                        self.ty(ty)

        out = [f"  (ir-module mtriple mqual {logos_str(m.triple)} {'true' if self.qual else 'false'})"]
        out.extend(self.type_lines)
        for struct in m.structs:
            out.append(
                "  "
                + call(
                    "ir-struct",
                    ["snames", "sbase", "scount"],
                    [logos_str(struct.name), "(vec-len sftys)", len(struct.fields)],
                )
            )
            for field in struct.fields:
                out.append("  (vec-push sftys " + self.ty(field) + ")")
        for enum in m.enums:
            out.append(
                "  " + call("ir-enum", ["enames", "ewords"], [logos_str(enum.name), enum.words])
            )
        for global_ in m.globals:
            out.append(
                "  "
                + call(
                    "ir-global",
                    ["gnames", "gdata"],
                    [logos_str(global_.name), logos_str(global_.data.decode("utf-8"))],
                )
            )
        for decl in m.declares:
            start = f"ds{len(out)}"
            out.append(f"  (let {start} :i64 (ir-sig-start sigtys))")
            for param in decl.params:
                out.append("  " + call("ir-sig-param", ["sigtys"], [self.ty(param)]))
            out.append(
                "  "
                + call(
                    "ir-declare",
                    ["dnames", "dsig", "dcnt", "dret"],
                    [logos_str(decl.name), start, len(decl.params), self.ty(decl.ret)],
                )
            )
        for index, fn_ in enumerate(m.functions):
            fid = f"f{index}"
            out.append(
                f"  (let {fid} :i64 "
                + call(
                    "ir-fn",
                    [
                        "fnames",
                        "fsyms",
                        "fint",
                        "fret",
                        "fbase",
                        "fcnt",
                        "fparam",
                        "fpc",
                        "blabels",
                        "pnames",
                    ],
                    [
                        logos_str(fn_.name),
                        logos_str(fn_.symbol),
                        "true" if fn_.internal else "false",
                        self.ty(fn_.ret),
                    ],
                )
                + ")"
            )
            for name, ty in fn_.params:
                out.append(
                    "  " + call("ir-param", ["pnames", "ptys"], [logos_str(name), self.ty(ty)])
                )
            for block in fn_.blocks:
                out.append(
                    "  "
                    + call(
                        "ir-block",
                        ["blabels"] + BLOCK_COLS + ["ops"],
                        [logos_str(block.label)],
                    )
                )
                for instr in block.instrs:
                    out.extend(self.instr(instr))
                out.append(self.term(block.term))
            out.append(
                "  "
                + call(
                    "ir-fn-end", ["fbase", "fcnt", "fparam", "fpc", "blabels", "pnames"], [fid]
                )
            )
        return "\n".join(out)


