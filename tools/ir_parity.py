#!/usr/bin/env python3
"""Generate the emitter's fixtures and ``src/logosc/emit_test.logos``.

The port has no lowerer yet, so the emitter is tested by construction: every
case below is a module built out of ``logos.ir`` values, emitted with
``logos.llvm.emit``, and written to ``src/logosc/fixtures/ir/<name>.ll``. The
generated Logos test builds the *same* module through ``src/logosc/ir.logos``'s
own constructors and compares its text with that file, byte for byte. Neither
side is transcribed by hand, so one changed spelling shows up as a failing case
instead of two files that drifted together.

A module the reference refuses fails this script, for the reason
``tools/types_parity.py`` gives about a type row: a case Python never agreed to
emit would be a green line comparing the port with nothing.

Three guards run before anything is written:

* every opcode in the vocabulary must appear in at least one case, so no
  printer branch is untested;
* a module with an unknown opcode must make the reference raise, so the
  refusal the emitter copies is still the reference's behaviour;
* a type variable must make ``type_text`` raise, and the fixture takes its
  expected text from that exception, so the port reproduces Python's words
  rather than a transcription.

A refusal with no Python counterpart at all (a dangling type id, a type child
with a newer id, a row whose type slot is unset) is a *port-only* fixture; its
header carries a third line saying so, and the generator compares the port's
message with itself there by design.

The generated test reads the fixtures by repository-relative path, so run the
suite from the repository root::

    python3 -m logos test src/logosc/emit_test.logos --opt -O0 --opt -O2

Regenerate with ``python3 tools/ir_parity.py``; the test is formatted with
``python3 -m logos fmt`` afterwards, so it is a fixed point of the formatter.
"""

