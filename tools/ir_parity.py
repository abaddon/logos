# The modules, built out of logos.ir values.


def blk(label, instrs, term):
    return IrBlock(label, list(instrs), term)


def fn(name, params, ret, blocks, symbol="", internal=False):
    return IrFn(name, list(params), ret, list(blocks), symbol, internal)


def module(globals_, functions, structs=(), enums=(), declares=()):
    return IrModule(
        TRIPLE,
        list(globals_),
        list(functions),
        declares=list(declares),
        structs=list(structs),
        enums=list(enums),
    )


def arith():
    return module(
        [],
        [
            fn(
                "max",
                [("v.0", I64), ("v.1", I64)],
                I64,
                [
                    blk(
                        "entry",
                        [
                            ("add", "%sum", I64, "%v.0", "%v.1"),
                            ("icmp", "%lt", "slt", I64, "%sum", "%v.1"),
                        ],
                        ("cbr", "%lt", "thenb", "elseb"),
                    ),
                    blk("thenb", [], ("br", "join")),
                    blk("elseb", [], ("br", "join")),
                    blk(
                        "join",
                        [("phi", "%p", I64, (("%sum", "thenb"), ("%v.1", "elseb")))],
                        ("ret", I64, "%p"),
                    ),
                ],
                symbol="lg.m.max",
                internal=True,
            )
        ],
    )


