def negative_builds() -> list[tuple[str, list[str], str, bool]]:
    """``(name, Logos lines, expected message, port_only)`` for the loud refusals.

    ``port_only`` says the reference has no module that reaches this check: the
    message is the port's, and the fixture's header records that.
    """
    def rig(*tys):
        """A header call plus the type arena, with one id per requested type."""
        tr = Translation()
        ids = [tr.ty(ty) for ty in tys]
        lines = [
            "  (ir-module mtriple mqual \"x86_64-unknown-linux-gnu\" false)",
            "\n".join(tr.type_lines),
        ]
        return lines, ids

    unknown_head, (i64, void) = rig(I64, VOID)
    unknown = [
        *unknown_head,
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"bad\" \"lg.m.bad\" true {void}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        "  "
        + call(
            "ir-binary",
            ROWS + RUNS,
            ["(ir-op-store)", logos_str("%x"), i64, logos_str("1"), logos_str("2")],
        ),
        f"  (ir-ret-void ops bbase bcnt bterm bty bhas bv1 bv2 bv3 {void})",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    no_term_head, (void_only,) = rig(VOID)
    no_term = [
        *no_term_head,
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"unterminated\" \"lg.m.unterminated\" true {void_only}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    missing_head, (mi64, menum) = rig(I64, PARSE)
    missing = [
        *missing_head,
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"no-enum\" \"lg.m.no-enum\" true {mi64}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        f"  (ir-alloca ops dests a b c d t1 t2 t3 n1 sst scn tst tcn svals tvals \"%e\" {menum})",
        f"  (ir-ret ops bbase bcnt bterm bty bhas bv1 bv2 bv3 {mi64} \"0\")",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    prim_head, (pi64,) = rig(I64)
    unknown_prim = [
        *prim_head,
        "  (let p0 :i64 (type-prim tags names elem extra pbase powner \"nope\"))",
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"nope\" \"lg.m.nope\" true {pi64}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        "  (ir-alloca ops dests a b c d t1 t2 t3 n1 sst scn tst tcn svals tvals \"%e\" p0)",
        f"  (ir-ret ops bbase bcnt bterm bty bhas bv1 bv2 bv3 {pi64} \"0\")",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    dangling_head, (di64,) = rig(I64)
    dangling = [
        *dangling_head,
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"dangling\" \"lg.m.dangling\" true {di64}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        "  (ir-alloca ops dests a b c d t1 t2 t3 n1 sst scn tst tcn svals tvals \"%e\" 99)",
        f"  (ir-ret ops bbase bcnt bterm bty bhas bv1 bv2 bv3 {di64} \"0\")",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    older = [
        "  (ir-module mtriple mqual \"x86_64-unknown-linux-gnu\" false)",
        "  (let _ :i64 (type-vec tags names elem extra pbase powner 2))",
    ]

    no_type_head, (ni64, nvoid) = rig(I64, VOID)
    no_type = [
        *no_type_head,
        f"  (let f0 :i64 (ir-fn fnames fsyms fint fret fbase fcnt fparam fpc blabels pnames \"untyped\" \"lg.m.untyped\" true {nvoid}))",
        "  (ir-block blabels bbase bcnt bterm bty bhas bv1 bv2 bv3 ops \"entry\")",
        "  (ir-alloca ops dests a b c d t1 t2 t3 n1 sst scn tst tcn svals tvals \"%e\" -1)",
        f"  (ir-ret ops bbase bcnt bterm bty bhas bv1 bv2 bv3 {ni64} \"0\")",
        "  (ir-fn-end fbase fcnt fparam fpc blabels pnames f0)",
    ]

    return [
        ("unknown-op", unknown, "unknown IR opcode 0", False),
        ("unknown-prim", unknown_prim, "no LLVM layout for type :nope", False),
        ("no-terminator", no_term, "block 'entry' has no terminator", False),
        ("missing-enum", missing, "no layout registered for enum 'parse-error'", False),
        ("dangling-type", dangling, "IR row 0 reads a type id the arena does not have", True),
        ("older-type", older, "type 0 has a child id that is not older", True),
        ("no-type", no_type, "IR row 0 has no type", True),
    ]


def build_test(modules, negatives) -> str:
    prelude = PRELUDE.replace("PORT_HDR_LITERAL", logos_str(PORT_HEADER))
    parts = [prelude.replace("HEADER_LITERAL", logos_str(HEADER))]
    tests = []
    for name, m, _ in modules:
        path = str(FIXTURES / (name + ".ll"))
        parts.append(module_case(name, m, path, name in QUALIFIED))
        tests.append(name)
    parts.append(type_text_case())
    parts.append(type_var_case())
    tests.extend(["type-text", "type-var"])
    for name, build, message, port_only in negatives:
        path = str(FIXTURES / (name + ".txt"))
        parts.append(negative_case(name, build, message, path, port_only))
        tests.append(name)

    for name in tests:
        func = f"t-case-{name.replace('-', '_')}"
        parts.append(
            f'(test emit-{name}\n  (expect (out "ok\\n")\n    (code 0)\n    (leaks 0))\n'
            f"  (println ({func})))"
        )
    return "\n\n".join(parts) + "\n"


def main() -> int:
    FIXTURES.mkdir(parents=True, exist_ok=True)

    written = []
    for name, m, must in MODULES:
        try:
            text = emit(m)
        except Exception as error:  # noqa: BLE001 - a refused module must stop the build
            raise SystemExit(f"case {name}: the reference refuses the module: {error}") from error
        for needle in must:
            if needle not in text:
                raise SystemExit(f"case {name}: expected {needle!r} in the emitted text")
        (FIXTURES / (name + ".ll")).write_text(HEADER + text, encoding="utf-8")
        written.append(name)

    host = type_host()
    emit(host)
    spellings = [type_text(ty) for _, ty in TYPE_TEXT]
    (FIXTURES / "type-text.txt").write_text(
        HEADER + "\n".join(spellings) + "\n", encoding="utf-8"
    )
    try:
        type_text(TypeVar("T"))
    except ValueError as error:
        type_var_message = str(error)
    else:
        raise SystemExit("the reference spells a type variable; the refusal has no row")
    # Python's own words, not a transcription: the port names the stored type
    # variable the way ``type_text`` does.
    (FIXTURES / "type-var.txt").write_text(
        HEADER + type_var_message + "\n", encoding="utf-8"
    )

    negatives = negative_builds()
    for name, _, message, port_only in negatives:
        header = PORT_HEADER if port_only else HEADER
        (FIXTURES / (name + ".txt")).write_text(header + message + "\n", encoding="utf-8")

    # Every opcode must be exercised, and the reference must still refuse one
    # it does not know.
    covered = set()
    for _, m, _ in MODULES:
        for fn_ in m.functions:
            for block in fn_.blocks:
                for instr in block.instrs:
                    covered.add(instr[0])
    missing = sorted(set(OPCODES) - covered)
    if missing:
        raise SystemExit(f"the cases do not exercise: {', '.join(missing)}")
    probe = module([], [fn("main", [], VOID, [blk("entry", [("nonesuch",)], ("ret", VOID, None))])])
    try:
        emit(probe)
    except ValueError:
        pass
    else:
        raise SystemExit("the reference accepted an unknown opcode")

    path = ROOT / "src/logosc/emit_test.logos"
    path.write_text(build_test(MODULES, negatives), encoding="utf-8")
    subprocess.run([sys.executable, "-m", "logos", "fmt", str(path)], cwd=ROOT, check=True)
    print(f"{path.relative_to(ROOT)}: {len(MODULES)} modules, {len(negatives)} refusals, {len(OPCODES)} opcodes")
    for name in written:
        print("  " + name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
