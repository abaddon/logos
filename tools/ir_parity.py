def qualified_unit():
    """A unit of two modules: ``shapes``'s struct and ``colors``'s enum.

    Python's lowerer spells both by the module that declared them, so the
    module carries the final names ``shapes.point`` and ``colors.tone``. The
    Logos arena records the same final names and says ``qual``; this case pins
    that the definition line and every use agree under ``mqual = 1``.
    """
    return module(
        [],
        [
            fn(
                "tag",
                [("v.0", COLORS_TONE)],
                I64,
                [
                    blk(
                        "entry",
                        [
                            ("alloca", "%s", SHAPES_POINT),
                            ("extractvalue", "%t", COLORS_TONE, I32, "%v.0", 0),
                            ("sext", "%w", I32, I64, "%t"),
                        ],
                        ("ret", I64, "%w"),
                    )
                ],
                symbol="lg.shapes.tag",
                internal=True,
            )
        ],
        structs=[IrStruct("shapes.point", (I8, I64))],
        enums=[IrEnum("colors.tone", 2)],
    )


def closure():
    env_fields = (I64, Ptr(I8))
    return module(
        [],
        [
            fn(
                "apply",
                [("env", Ptr(I8)), ("v.0", I64)],
                I64,
                [blk("entry", [], ("ret", I64, "%v.0"))],
                symbol="lg.m.apply",
                internal=True,
            ),
            fn(
                "call-with",
                [("v.0", I64), ("v.1", FN_ENV)],
                I64,
                [
                    blk(
                        "entry",
                        [
                            ("extractvalue", "%env", FN_ENV, Ptr(I8), "%v.1", 0),
                            ("extractvalue", "%code", FN_ENV, Ptr(I8), "%v.1", 1),
                            ("fnptr", "%f", I64, (Ptr(I8), I64), "%code"),
                            ("icall", "%r", I64, (Ptr(I8), I64), "%f", ("%env", "%v.0")),
                        ],
                        ("ret", I64, "%r"),
                    )
                ],
                symbol="lg.m.call-with",
                internal=True,
            ),
            fn(
                "address",
                [],
                Ptr(I8),
                [blk("entry", [("faddr", "%a", "lg.m.apply")], ("ret", Ptr(I8), "%a"))],
                symbol="lg.m.address",
                internal=True,
            ),
            fn(
                "capture",
                [("v.0", I64)],
                Ptr(I8),
                [
                    blk(
                        "entry",
                        [
                            ("allocarec", "%env", env_fields),
                            ("geprec", "%f0", env_fields, "%env", 0),
                            ("store", I64, "%v.0", "%f0"),
                            ("geprec", "%f1", env_fields, "%env", 1),
                            ("store", Ptr(I8), "null", "%f1"),
                            ("bitcastout", "%out", env_fields, Ptr(I8), "%env"),
                        ],
                        ("ret", Ptr(I8), "%out"),
                    )
                ],
                symbol="lg.m.capture",
                internal=True,
            ),
            fn(
                "unpack",
                [("v.0", Ptr(I8))],
                Ptr(I8),
                [
                    blk(
                        "entry",
                        [
                            ("bitcastrec", "%rec", env_fields, Ptr(I8), "%v.0"),
                            ("geprec", "%slot", env_fields, "%rec", 1),
                            ("load", "%code", Ptr(I8), "%slot"),
                        ],
                        ("ret", Ptr(I8), "%code"),
                    )
                ],
                symbol="lg.m.unpack",
                internal=True,
            ),
        ],
    )


